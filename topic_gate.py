def has_domain_evidence(norm_text: str, dish_or_category_named: bool = False) -> bool:
    """В реплике гостя есть слова из нашей темы (еда, цены, бронь, адрес/часы, приветствие, отзыв, дата/число) или названо блюдо.
    Просьба «посоветуй …» без еды — не повод: «посоветуй другие рестораны» -> не по теме."""
    t = norm_text.strip()
    if re.search(r"как (?:приготов|сварит|пожарит|испечь|сделат[ь] )|рецепт", t):
        return False                                                     # «как приготовить борщ» — не про наш ресторан
    if not t or dish_or_category_named:
        return True
    if followup_shape(t) and re.search(r"входит|состав|стоит|цен|остр|мяс|вкусн|весит|порци|калори|вегет|аллерг|рыб", t):
        return True                                                      # «а что туда входит?» — вопрос про блюдо, роутер уточнит, про какое
    if _EVID.search(t) is None:
        return False
    if _STRONG.search(t) is None:                                        # только приветствие / дата / число: «Переведи на английский привет», «Реши 2x+3=7»
        rest = _WEAK.sub(" ", t)
        extra = [w for w in re.findall(r"[a-zа-я]{4,}", rest) if not _QWORDS.match(w)]
        if extra:
            return False
    if REC.search(t) and not _strong_evidence(t):
        content = [w for w in re.findall(r"[a-zа-я]{3,}", t) if not _FILLER.match(w)]
        return not content                                               # «посоветуй что-нибудь» — да; «посоветуй рестораны» — нет
    return True


def _strong_evidence(t: str) -> bool:
    rest = REC.sub(" ", t)
    return _EVID.search(rest) is not None and any(
        re.search(p, rest) for p in (FOOD.replace("порекоменд|посовет|советуй|рекоменд|", ""), BOOK, SERVICE, FEEDBACK, NOT_ON_MENU_STEMS))


def text_kinds(answer: str) -> set[str]:
    """Что за ответ выдала модель (по тексту): фирменные блюда, часы работы, адрес, реакция на отзыв."""
    kinds = {k for k, rx in ANSWER_KINDS if rx.search(answer or "")}
    if "lunch" in kinds:                                                 # часы бизнес-ланча — часть ответа про ланчи
        kinds.discard("hours")
    if "about" in kinds:                                                 # рассказ о ресторане включает адрес и часы — отдельно их слов не требуем
        kinds -= {"address", "hours"}
    return kinds


def output_ok(kind: str, texts: Iterable[str]) -> bool:
    """Хоть в одной из реплик гостя (текущая, а для коротких «а …» — ещё и прошлая) есть слова, оправдывающие ответ типа kind."""
    rx = EVIDENCE.get(kind)
    return rx is None or any(rx.search(t) for t in texts)


_GREET = re.compile(r"^\s*(?:(?:привет(?:ствую)?|здравствуй(?:те)?|здрасьте|добр(?:ый|ое|ого|ой) (?:день|вечер|утро|утра|вечера|ночи)|доброго времени суток|хай|хеллоу|hello|hi)\b[\s,.!;:-]*)+", re.I)


def strip_greeting(text: str) -> str:
    """«Добрый день. Покажите меню» -> «Покажите меню» (для разбора; одно приветствие без вопроса остаётся как есть)."""
    t = _GREET.sub("", text, count=1).strip()
    return t if t else text


def followup_shape(norm_now: str) -> bool:
    """Короткое продолжение прошлого ответа: «а что туда входит?», «а в нём есть мясо?», «и сколько он стоит?» — без слов темы, но с отсылкой."""
    words = norm_now.split()
    return len(words) <= 7 and bool(norm_now.startswith(("а ", "и ", "ну ")) or re.search(
        r"\b(?:он|она|оно|они|его|её|ее|нём|нем|ней|неё|них|туда|там|этом|этого|это|тоже|ещё|еще|другое|другие|подешевле|подороже)\b", norm_now))


def evidence_texts(norm_now: str, norm_prev: Optional[str]) -> list[str]:
    """Реплики, в которых ищем оправдание ответа: текущая; если она короткое продолжение («а в выходные?», «а он острый?») — ещё и прошлая."""
    words = norm_now.split()
    follow = len(words) <= 5 and (norm_now.startswith(("а ", "и ", "ну ")) or re.search(
        r"\b(?:он|она|оно|они|его|её|ее|туда|там|тоже|ещё|еще|другое|другие|подешевле|подороже)\b", norm_now))
    return [norm_now] + ([norm_prev] if follow and norm_prev else [])
